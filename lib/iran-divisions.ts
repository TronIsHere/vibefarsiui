const collator = new Intl.Collator("fa");

/** All 31 provinces in Persian alphabetical order. */
export const PROVINCES: Province[] = RAW.map(([name, capital, others]) => ({
  name,
  capital,
  cities: [capital, ...others.split("، ").sort(collator.compare)],
}));

/** Province names only, for a select or combobox. */
export const PROVINCE_NAMES: string[] = PROVINCES.map((p) => p.name);

/** Cities of a province (capital first), or [] for an unknown name. */
export function citiesOf(province: string): string[] {
  return PROVINCES.find((p) => p.name === province)?.cities ?? [];
}

/** Every province that has a city with this name (a few names repeat, like «حاجی‌آباد»). */
export function provincesOf(city: string): string[] {
  return PROVINCES.filter((p) => p.cities.includes(city)).map((p) => p.name);
}

/** True when the pair is in the dataset. */
export function isValidAddress(province: string, city: string): boolean {
  return citiesOf(province).includes(city);
}
